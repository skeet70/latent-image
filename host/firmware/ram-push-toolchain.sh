#!/usr/bin/env bash
# Writes the RamPushToolchain module: the RAM-push relink tools' resolved store
# paths, a SHA-256 over those paths and a SHA-256 over the builder sources.
# usage: OUT SHA256SUM SORT BASH_STORE_PATH CLANG_STORE_PATH LD_LLD_STORE_PATH OBJCOPY_STORE_PATH NM_STORE_PATH OBJDUMP_STORE_PATH SHA256SUM_STORE_PATH SOURCE...
set -euo pipefail

out="$1" sha256sum="$2" sort="$3"
shift 3
labels=(bash clang ld.lld llvm-objcopy llvm-nm llvm-objdump)
paths=()
for label in "${labels[@]}"; do
  IFS= read -r path < "$1"
  paths+=("$path")
  shift
done
IFS= read -r sha_path < "$1"
shift
coreutils_bin="${sha_path%/*}"

toolchain_digest="$(
  for index in "${!labels[@]}"; do printf '%s %s\n' "${labels[$index]}" "${paths[$index]}"; done
  printf 'coreutils %s\n' "$coreutils_bin"
)"
toolchain_digest="$(printf '%s\n' "$toolchain_digest" | "$sha256sum")"
sources_digest="$(printf '%s\n' "$@" | LC_ALL=C "$sort" | while IFS= read -r source; do "$sha256sum" "$source"; done | "$sha256sum")"

{
  printf -- '-- Generated by //host/firmware:ram-push-toolchain-module.\n'
  printf 'module RamPushToolchain (RamPushToolchain (..), ramPushToolchain, ramPushToolchainDigest, recipeBankBuilderDigest) where\n\n'
  printf 'data RamPushToolchain = RamPushToolchain\n'
  printf '  { toolBash :: FilePath, toolClang :: FilePath, toolLdLld :: FilePath\n'
  printf '  , toolObjcopy :: FilePath, toolNm :: FilePath, toolObjdump :: FilePath\n'
  printf '  , toolCoreutilsBin :: FilePath }\n\n'
  printf 'ramPushToolchain :: RamPushToolchain\n'
  printf 'ramPushToolchain = RamPushToolchain'
  for path in "${paths[@]}" "$coreutils_bin"; do printf ' "%s"' "$path"; done
  printf '\n\n'
  printf -- '-- | SHA-256 over the tool labels and store paths above.\n'
  printf 'ramPushToolchainDigest :: String\n'
  printf 'ramPushToolchainDigest = "%s"\n\n' "${toolchain_digest%% *}"
  printf -- '-- | SHA-256 over `sha256sum` lines of build-recipe-bank'"'"'s workspace Haskell sources, sorted by path.\n'
  printf 'recipeBankBuilderDigest :: String\n'
  printf 'recipeBankBuilderDigest = "%s"\n' "${sources_digest%% *}"
} > "$out"
