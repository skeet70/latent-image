#!/usr/bin/env bash
# Writes a builder-digest module: a SHA-256 over `sha256sum` lines of a
# builder's workspace Haskell sources, sorted by path.
# usage: OUT TARGET MODULE BINDING SHA256SUM SORT SOURCE...
set -euo pipefail

out="$1" target="$2" module="$3" binding="$4" sha256sum="$5" sort="$6"
shift 6
digest="$(printf '%s\n' "$@" | LC_ALL=C "$sort" | while IFS= read -r source; do "$sha256sum" "$source"; done | "$sha256sum")"
{
  printf -- '-- Generated by //host/firmware:%s.\n' "$target"
  printf 'module %s (%s) where\n\n' "$module" "$binding"
  printf '%s :: String\n' "$binding"
  printf '%s = "%s"\n' "$binding" "${digest%% *}"
} > "$out"
