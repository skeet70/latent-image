#!/usr/bin/env bash
# Writes the ClassicChromeRamBuilder module: a SHA-256 over `sha256sum` lines
# of build-classic-chrome-ram's workspace Haskell sources, sorted by path.
# usage: OUT SHA256SUM SORT SOURCE...
set -euo pipefail

out="$1" sha256sum="$2" sort="$3"
shift 3
digest="$(printf '%s\n' "$@" | LC_ALL=C "$sort" | while IFS= read -r source; do "$sha256sum" "$source"; done | "$sha256sum")"
{
  printf -- '-- Generated by //host/firmware:classic-chrome-ram-builder-module.\n'
  printf 'module ClassicChromeRamBuilder (classicChromeRamBuilderDigest) where\n\n'
  printf 'classicChromeRamBuilderDigest :: String\n'
  printf 'classicChromeRamBuilderDigest = "%s"\n' "${digest%% *}"
} > "$out"
