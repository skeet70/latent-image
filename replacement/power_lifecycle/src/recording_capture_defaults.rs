fn put_word(bytes: &mut [u8], offset: usize, value: u32) { bytes[offset..offset + 4].copy_from_slice(&value.to_le_bytes()); }

pub fn initialize(settings: &mut [u8; 0x3e8], work: &mut [u8; 0x9f0]) {
    for (start, end) in [(0, 0x99), (0x9c, 0xd0), (0xd4, 0xdc), (0xe0, 0xe4), (0xe8, 0x127), (0x128, 0x33b), (0x33c, 0x3ad), (0x3b0, 0x3bc), (0x3d8, 0x3dc), (0x3e0, 0x3e8)] {
        settings[start..end].fill(0);
    }
    for (offset, value) in [(0x14, 6), (0x4c, 3), (0x50, 4), (0x54, 4), (0x68, 2), (0x9c, 13), (0xb8, 2), (0xbc, 0xa4), (0xc0, 0x81), (0xec, 0x41), (0x104, 0xd0), (0x10c, 2), (0x114, 1), (0x140, 1), (0x308, 2), (0x30c, 2), (0x32c, 1), (0x384, 1), (0x3b0, 2)] {
        put_word(settings, offset, value);
    }
    for (start, end) in [(0, 0xe9), (0xea, 0xed), (0xee, 0xf1), (0xf4, 0x105), (0x106, 0x109), (0x10c, 0x125), (0x126, 0x142), (0x144, 0x168), (0x170, 0x176), (0x178, 0x1e0), (0x930, 0x934), (0x940, 0x944), (0x984, 0x988), (0x990, 0x9a6), (0x9a8, 0x9ac), (0x9ec, 0x9f0)] {
        work[start..end].fill(0);
    }
    for (offset, value) in [(0xf4, 0xffff_c180), (0x120, 1), (0x1cc, 1), (0x1d0, 4)] { put_word(work, offset, value); }
    work[0x104] = 1;
    work[0x106..0x108].copy_from_slice(&0x8cu16.to_le_bytes());
    work[0x154] = 0x40;
    work[0x155] = 13;
    work[0x168..0x16a].copy_from_slice(&100u16.to_le_bytes());
}

#[cfg(test)]
mod tests {
    use super::initialize;

    #[test]
    fn fallback_defaults_preserve_reserved_and_unwritten_bytes() {
        let mut settings = [0xa5; 0x3e8];
        let mut work = [0x5a; 0x9f0];
        initialize(&mut settings, &mut work);
        assert_eq!(&settings[0x14..0x18], &[6, 0, 0, 0]);
        assert_eq!(&settings[0x4c..0x58], &[3, 0, 0, 0, 4, 0, 0, 0, 4, 0, 0, 0]);
        for offset in [0x99, 0xd0, 0xdc, 0xe4, 0x127, 0x33b, 0x3ad, 0x3bc, 0x3dc] { assert_eq!(settings[offset], 0xa5); }
        for offset in [0xe9, 0xed, 0xf1, 0x105, 0x109, 0x125, 0x142, 0x16a, 0x176, 0x1e0, 0x934, 0x9a6] { assert_eq!(work[offset], 0x5a); }
        assert_eq!(&work[0x104..0x108], &[1, 0x5a, 0x8c, 0]);
        assert_eq!(&work[0x168..0x16c], &[100, 0, 0x5a, 0x5a]);
        assert_eq!(&work[0xf4..0xf8], &[0x80, 0xc1, 0xff, 0xff]);
    }
}
