pub const fn request_limit(request: u32) -> Option<Property> {
    match request {
        1 => Some(Property(0x8cf4)),
        2 => Some(Property(0x8cf5)),
        3 => Some(Property(0x8cfa)),
        4 => Some(Property(0x8cf6)),
        5 => Some(Property(0x8cf7)),
        6 => Some(Property(0x8cf8)),
        7..=12 => Some(Property(0x8cf9)),
        14 => Some(Property(0x8cfb)),
        _ => None,
    }
}
