/// An adjustment profile's table row (0xf83484, with its option setting from 0xf80850).
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct ProfileRecord {
    /// The range set when `fixed_range_set`, else the setting holding the range class.
    pub range_key: u32,
    pub fixed_range_set: bool,
    /// A selection of 100 or more raises the selected level by 100 (0xf78e0c).
    pub raises_with_percent: bool,
    pub scale: u32,
    pub secondary_gate: bool,
    /// The column of the range class table.
    pub policy: u32,
    pub tertiary_gate: bool,
    pub range_limit: u32,
    pub adjustment: u32,
    pub state: u8,
    pub auxiliary: u8,
    pub option: Property,
}

const fn profile(
    range_key: u32,
    fixed_range_set: u8,
    control: u8,
    scale: u32,
    secondary_gate: u8,
    policy: u32,
    tertiary_gate: u8,
    range_limit: u32,
    adjustment: u32,
    state: u8,
    auxiliary: u8,
    option: u32,
) -> ProfileRecord {
    ProfileRecord {
        range_key,
        fixed_range_set: fixed_range_set == 1,
        raises_with_percent: control == 0,
        scale,
        secondary_gate: secondary_gate == 1,
        policy,
        tertiary_gate: tertiary_gate == 1,
        range_limit,
        adjustment,
        state,
        auxiliary,
        option: Property(option),
    }
}

