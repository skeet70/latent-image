/// (0xf8127c), its auxiliary bound and level settings (0xf822cc) and its neighbours (0xf869dc).
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct RangeSet {
    pub selections: [Property; 3],
    pub cap: Property,
    pub bounds: [[Property; 2]; SELECTORS],
    pub auxiliary: [[Property; 2]; SELECTORS],
    pub neighbours: Neighbours,
}

const fn pairs(raw: [[u32; 2]; SELECTORS]) -> [[Property; 2]; SELECTORS] {
    let mut pairs = [[Property(0); 2]; SELECTORS];
    let mut index = 0;
    while index < SELECTORS {
        pairs[index] = [Property(raw[index][0]), Property(raw[index][1])];
        index += 1;
    }
    pairs
}

const fn range_set(selections: [u32; 3], cap: u32, bounds: [[u32; 2]; SELECTORS], auxiliary: [[u32; 2]; SELECTORS], neighbours: Neighbours) -> RangeSet {
    RangeSet {
        selections: [Property(selections[0]), Property(selections[1]), Property(selections[2])],
        cap: Property(cap),
        bounds: pairs(bounds),
        auxiliary: pairs(auxiliary),
        neighbours,
    }
}

