#[test]
fn selection_flags_have_independent_fields_and_widths() {
    let cases: [(fn(&mut SelectionRequest), usize); 5] = [
        (|request| request.first = true, 0),
        (|request| request.unrestored = true, 80),
        (|request| request.rate_flag = true, 172),
        (|request| request.scale_change = true, 200),
        (|request| request.recording = true, 220),
    ];
    for (set, offset) in cases {
        let mut request = SelectionRequest::default();
        set(&mut request);
        let mut expected = [0; 228];
        expected[offset] = 1;
        assert_eq!(selection_request(&request, LIVE_REGION), expected);
    }
}

#[test]
fn selection_result_flags_are_independent_and_accept_any_nonzero_word() {
    for (shot, kept) in [(0u32, 0u32), (2, 0), (0, 0x10000), (0x80000000, 1)] {
        let mut bytes = [0; 276];
        bytes[208..212].copy_from_slice(&shot.to_le_bytes());
        bytes[216..220].copy_from_slice(&kept.to_le_bytes());
        assert_eq!(selection_result(SharedAddress(7), &bytes), SelectionResult {
            address: SharedAddress(7), shot_data: shot != 0, keeps_program: kept != 0, ..SelectionResult::default()
        });
    }
}
