    assert_eq!(hmac_sha1(&[0x0b; 20], &[b"Hi There"]), [0xb6,0x17,0x31,0x86,0x55,0x05,0x72,0x64,0xe2,0x8b,0xc0,0xb6,0xfb,0x37,0x8c,0x8e,0xf1,0x46,0xbe,0x00]);
