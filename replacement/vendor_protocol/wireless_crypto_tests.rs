#[test]
fn rfc3394_unwrap_vector_and_integrity_rejection() {
    let key = [0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f];
    let mut wrapped = [0x1f,0xa6,0x8b,0x0a,0x81,0x12,0xb4,0x47,0xae,0xf3,0x4b,0xd8,0xfb,0x5a,0x7b,0x82,0x9d,0x3e,0x86,0x23,0x71,0xd2,0xcf,0xe5];
    let mut output = [0; 16];
    assert_eq!(unwrap_key_data(&key, &wrapped, &mut output), Ok(16));
    assert_eq!(output, [0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff]);
    let mut encoded = [0; 24];
    assert_eq!(wrap_key_data(&key, &output, &mut encoded), Ok(24));
    assert_eq!(encoded, wrapped);
    wrapped[7] ^= 1;
    assert_eq!(unwrap_key_data(&key, &wrapped, &mut output), Err(KeyWrapError::Integrity));
    assert_eq!(output, [0; 16]);
    assert_eq!(unwrap_key_data(&key, &wrapped[..16], &mut output), Err(KeyWrapError::Length));
    assert_eq!(unwrap_key_data(&key, &wrapped, &mut output[..15]), Err(KeyWrapError::Length));
}

#[test]
fn authenticator_checks_all_bytes_and_length() {
    assert!(equal_authenticator(&[7; 16], &[7; 16]));
    assert!(!equal_authenticator(&[7; 16], &[7; 15]));
    for index in 0..16 { let mut altered = [7; 16]; altered[index] ^= 1; assert!(!equal_authenticator(&[7; 16], &altered)); }
}
