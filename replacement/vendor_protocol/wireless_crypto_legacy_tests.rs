use super::{hmac_md5, md5, rc4_skip, LegacyError};

#[test]
fn rfc1321_md5_vectors() {
    assert_eq!(md5(&[b""]), [0xd4,0x1d,0x8c,0xd9,0x8f,0x00,0xb2,0x04,0xe9,0x80,0x09,0x98,0xec,0xf8,0x42,0x7e]);
    assert_eq!(md5(&[b"a", b"bc"]), [0x90,0x01,0x50,0x98,0x3c,0xd2,0x4f,0xb0,0xd6,0x96,0x3f,0x7d,0x28,0xe1,0x7f,0x72]);
    assert_eq!(md5(&[b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789"]), [0xd1,0x74,0xab,0x98,0xd2,0x77,0xd9,0xf5,0xa5,0x61,0x1c,0x2c,0x9f,0x41,0x9d,0x9f]);
}
#[test]
fn rfc2202_hmac_md5_vectors() {
    assert_eq!(hmac_md5(&[0x0b;16], &[b"Hi There"]), [0x92,0x94,0x72,0x7a,0x36,0x38,0xbb,0x1c,0x13,0xf4,0x8e,0xf8,0x15,0x8b,0xfc,0x9d]);
    assert_eq!(hmac_md5(&[0xaa;80], &[b"Test Using Larger Than Block-Size Key - Hash Key First"]), [0x6b,0x1a,0xb7,0xfe,0x4b,0xd7,0xbf,0x8f,0x0b,0x62,0xe6,0xce,0x61,0xb9,0xd0,0xcd]);
}
#[test]
fn rfc6229_rc4_stream_and_drop256() {
    let key = [1,2,3,4,5];
    let mut first = [0;16]; rc4_skip(&key,0,&mut first).unwrap();
    assert_eq!(first,[0xb2,0x39,0x63,0x05,0xf0,0x3d,0xc0,0x27,0xcc,0xc3,0x52,0x4a,0x0a,0x11,0x18,0xa8]);
    let mut dropped = [0;16]; rc4_skip(&key,256,&mut dropped).unwrap();
    assert_eq!(dropped,[0x1c,0xfc,0xf6,0x2b,0x03,0xed,0xdb,0x64,0x1d,0x77,0xdf,0xcf,0x7f,0x8d,0x8c,0x93]);
    let mut unchanged=[1,2]; assert_eq!(rc4_skip(&[],0,&mut unchanged),Err(LegacyError::EmptyKey)); assert_eq!(unchanged,[1,2]);
}
