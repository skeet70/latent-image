{-# LANGUAGE GHC2021 #-}

-- Generates the owned picker table (`picker.rs` PickerTable expression) and a
-- JSON report of its sources and cross-checks from pinned inputs.
module Main where

import Control.Monad (forM, forM_, unless, when)
import qualified Data.Aeson as J
import qualified Data.ByteString as B
import qualified Data.ByteString.Lazy as BL
import Emulation.Sha256 (sha256, sha256Hex)
import Replacement.ModalRuntime.PickerTable
import System.Directory (doesPathExist)
import System.Environment (getArgs)

data Pinned = Pinned {pinnedFlag :: String, pinnedName :: String, pinnedSha256 :: String}

pins :: [Pinned]
pins =
  [ Pinned "--image5" "image5" "3cd501c07533938ae4d9347616986fd1649005a588c36b5abf05e36ef4fd892a"
  , Pinned "--image4" "image4" "f2e2acab892dafeed85171f6870a411f0a2d5eae10921b86a24630d401dcff16"
  , Pinned "--tables" "menu-tables" "7fa536b6f4ab72205be57f407ce7224fa0bbc397aca2061ad2fac3e14ba2021d"
  , Pinned "--census" "census-5" "5fb2f91c4eef1e53aa89c5c8829de1043f36f8ac976cc9d74f7db7aa754316ea"
  , Pinned "--manifest" "manifest" "f27b35628371e150cdc0cfea84b11424b52c8022f7604f832a04bb890273cd67"
  ]

pickerCount :: Int
pickerCount = 20

decodeNamed :: J.FromJSON a => String -> B.ByteString -> IO a
decodeNamed name = either (\reason -> fail (name ++ ": " ++ reason)) pure . J.eitherDecodeStrict

main :: IO ()
main = do
  arguments <- getArgs
  let required name = case dropWhile (/= name) arguments of _ : value : _ -> pure value; _ -> fail ("missing " ++ name)
  outPath <- required "--out"
  reportPath <- required "--report"
  forM_ [outPath, reportPath] $ \path -> do
    exists <- doesPathExist path
    when exists (fail (path ++ " already exists"))
  loaded <- forM pins $ \pin -> do
    bytes <- B.readFile =<< required (pinnedFlag pin)
    let digest = sha256Hex (sha256 bytes)
    unless (digest == pinnedSha256 pin) (fail (pinnedName pin ++ " identity differs: sha256 " ++ digest))
    pure (pinnedName pin, bytes)
  let bytesOf name = maybe (fail ("unloaded " ++ name)) pure (lookup name loaded)
  image5 <- bytesOf "image5"
  image4 <- bytesOf "image4"
  tables <- decodeNamed "menu-tables" =<< bytesOf "menu-tables"
  census <- decodeNamed "census-5" =<< bytesOf "census-5"
  manifest <- decodeNamed "manifest" =<< bytesOf "manifest"
  let inputs = Inputs (Image 0xbf1a00 image5) (Image 0x61c400 image4) tables census manifest
  generated <- either fail pure (generate contractCells inputs)
  let count = length (generatedNodes generated)
  unless (count == pickerCount) (fail (show count ++ " picker nodes, " ++ show pickerCount ++ " required"))
  let digests = [(pinnedName pin, pinnedSha256 pin) | pin <- pins]
      header =
        [ "Generated by //replacement/modal_runtime:picker-table from owner-supplied images; not for redistribution."
        ]
          ++ [name ++ " sha256 " ++ digest | (name, digest) <- digests]
  writeFile outPath (rustTable header generated)
  BL.writeFile reportPath (J.encode (reportJson digests generated))
  putStrLn
    ( "wrote " ++ outPath ++ " and " ++ reportPath ++ "; nodes=" ++ show count
        ++ "; cells=" ++ show (length (generatedCells generated))
    )
