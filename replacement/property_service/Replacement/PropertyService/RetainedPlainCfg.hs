-- | RSB instructions whose encodings fall in retired property code.
data RsbRole
  = GridHorizontalAlignment
  | GridVerticalAlignment
  | ChoiceListFirstSpan
  | ChoiceListSecondSpan
  | MenuTreeRowOffset
  | RecordTagCompare
  | HalfwordDeltaA
  | HalfwordDeltaB
  | LocalDifference
  | ByteDifference

data PlainBinding = PlainBinding FunctionBinding [(GuestAddress, RsbRole)]

plainCfgClosures :: [(ScanImage, Image)] -> [ClosedSite]
plainCfgClosures images =
  [ closed
  | Just image <- [imageFor ScanPlain images]
  , PlainBinding binding sites <- bindings
  , closed <- instructionSites ScanPlain image binding [(site, roleEncoding role) | (site, role) <- sites]
  ]

roleEncoding :: RsbRole -> Word32
roleEncoding role = case role of
  GridHorizontalAlignment -> 0x00625005
  GridVerticalAlignment -> 0x00626006
  ChoiceListFirstSpan -> 0x00621007
  ChoiceListSecondSpan -> 0x00621007
  MenuTreeRowOffset -> 0x00623006
  RecordTagCompare -> 0x00622006
  HalfwordDeltaA -> 0x00630000
  HalfwordDeltaB -> 0x00630000
  LocalDifference -> 0x00622001
  ByteDifference -> 0x00624004

plain :: GuestAddress -> [Word32] -> [(GuestAddress, RsbRole)] -> PlainBinding
plain entry words' = PlainBinding (FunctionBinding 0x1100000 entry words')

