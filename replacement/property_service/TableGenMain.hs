{-# LANGUAGE GHC2021 #-}
{-# LANGUAGE OverloadedStrings #-}

-- | Classifies every property of the canonical X-M1 1.50 image4 getter and setter tables and writes
-- the owned service's Rust property and slot tables and a classification record.
module Main (main) where

import Control.Monad (unless, when)
import Data.Aeson (encode, object, (.=))
import qualified Data.ByteString as B
import qualified Data.ByteString.Lazy as L
import PropertyFields (PropertyId (..))
import Replacement.PropertyService.ClassRecord
import Replacement.PropertyService.Classify
import Replacement.PropertyService.Encoding
import ServiceInventory (Image (..), digest)
import System.Directory (doesPathExist)
import System.Environment (getArgs)

image4Sha256 :: String
image4Sha256 = "f2e2acab892dafeed85171f6870a411f0a2d5eae10921b86a24630d401dcff16"

rustEntry :: Property -> EncodedEntry -> String
rustEntry (Property (PropertyId identifier) _ _ verdict) (EncodedEntry word) = "    Entry(" ++ hex word ++ "), // " ++ hex identifier ++ " " ++ note ++ "\n"
  where
    note = case verdict of
      Owned (OwnedField _) -> "field"
      Owned (OwnedSlotField _) -> "slot field"
      Owned OwnedUnassigned -> "unassigned"
      Delegated reason -> "delegated " ++ reasonLabel reason

rustSlot :: PropertyId -> EncodedSlot -> String
rustSlot (PropertyId identifier) (EncodedSlot word) = "    Slot(" ++ hex word ++ "), // " ++ hex identifier ++ "\n"

main :: IO ()
main = do
  args <- getArgs
  case args of
    [image4Path, rustOutput, classificationOutput] -> do
      mapM_ (\path -> doesPathExist path >>= \exists -> when exists (fail (path ++ " already exists"))) [rustOutput, classificationOutput]
      bytes <- B.readFile image4Path
      unless (digest bytes == image4Sha256) (fail "image4 is not canonical X-M1 1.50")
      properties <- either fail pure (classify (Image "image4" image4Path 0x61c400 bytes))
      EncodedTables entries slots <- either (fail . show) pure (encodeTables (map propertyClass properties))
      let slotIds = [identifier | Property identifier _ _ (Owned (OwnedSlotField _)) <- properties]
          rust = concat
            [ "// Generated by //replacement/property_service:table-gen from image4 sha256 ", image4Sha256, ". Do not edit.\n"
            , "use crate::table::{Entry, Slot};\n\n"
            , "pub static PROPERTIES: [Entry; ", show (length properties), "] = [\n"
            , concat (zipWith rustEntry properties entries)
            , "];\n\n"
            , "pub static SLOTS: [Slot; ", show (length slots), "] = [\n"
            , concat (zipWith rustSlot slotIds slots)
            , "];\n"
            ]
      writeFile rustOutput rust
      L.writeFile classificationOutput (encode (object
        [ "schemaVersion" .= (1 :: Int), "image4Sha256" .= image4Sha256
        , "encoding" .= encodingDescription
        , "summary" .= summaryValue properties
        , "properties" .= map classValue properties
        ]) <> "\n")
    _ -> fail "usage: table-gen IMAGE4 RUST_OUTPUT CLASSIFICATION_JSON"
